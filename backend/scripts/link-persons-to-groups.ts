async function main() {
  await mongoose.connect(process.env.MONGODB_URI);
  const db = mongoose.connection.db;

  const allGroups = await db.collection('groups').find({}).toArray();
  const groupMap: Record<string, string> = {};
  for (const g of allGroups) { groupMap[g.name] = g._id.toString(); }

  const allPersons = await db.collection('persons').find({}).toArray();
  const noGroup = allPersons.filter((p: any) => !p.groupIds || p.groupIds.length === 0);

  let updated = 0, skipped = 0;
  for (const person of noGroup) {
    const name = person.name.trim();
    let groups = EXACT_MAP[name];
    if (!groups) groups = fuzzyMatch(name);
    if (groups && groups.length > 0) {
      const uniqueGroups = [...new Set(groups)];
      const groupIds = uniqueGroups.map((g: string) => groupMap[g]).filter(Boolean);
      if (groupIds.length > 0) {
        await db.collection('persons').updateOne(
          { _id: person._id },
          { $set: { groupIds: groupIds.map((id: string) => new mongoose.Types.ObjectId(id)) } }
        );
        updated++;
      } else { skipped++; }
    } else { skipped++; }
  }

  console.log('更新: ' + updated + '  跳过: ' + skipped);

  const after = await db.collection('persons').find({}).toArray();
  const stillNone = after.filter((p: any) => !p.groupIds || p.groupIds.length === 0);
  console.log('未关联: ' + stillNone.length);
  for (const p of stillNone) console.log('  ' + p.name);

  await mongoose.disconnect();
}

function fuzzyMatch(name: string): string[] {
  const r: string[] = [];
  if (/清(军|政府|廷|朝)/.test(name)) r.push('清廷');
  if (/太平(天|军)/.test(name)) r.push('太平天国');
  if (/英(国|军)/.test(name)) r.push('外国势力');
  if (/法(国|军)/.test(name)) r.push('外国势力');
  if (/日本|日军|日寇/.test(name)) r.push('日本侵略军');
  if (/中共|共产党|红军|八路军|新四军|解放军|根据地/.test(name)) r.push('中国共产党');
  if (/国民(党|政府|革命军)|国军/.test(name)) r.push('国民党');
  if (/北洋|军阀|直系|皖系|奉系/.test(name)) r.push('军阀');
  if (/革命/.test(name)) r.push('革命派');
  return [...new Set(r)];
}

