async function main() {
  await mongoose.connect(process.env.MONGODB_URI);
  const db = mongoose.connection.db;

  console.log('=== 清空 groups 集合 ===');
  await db.collection('groups').deleteMany({});

  console.log('\n=== 创建 9 个一级阵营 ===');
  const primaryMap: Record<string, string> = {};
  for (const g of PRIMARY_GROUPS) {
    const result = await db.collection('groups').insertOne({
      name: g.name,
      description: g.description,
      parentId: null,
      type: 'primary',
      createdAt: new Date(),
      updatedAt: new Date(),
    });
    primaryMap[g.name] = result.insertedId.toString();
    console.log('  ✓ ' + g.name + ' (' + g.description + ')');
  }

  console.log('\n=== 创建二级子群体 ===');
  const subGroupMap: Record<string, string> = {};
  for (const [name, parentName, desc] of SUB_GROUPS) {
    const parentId = primaryMap[parentName];
    if (!parentId) { console.log('  ✗ 父群体不存在: ' + parentName); continue; }
    const result = await db.collection('groups').insertOne({
      name, description: desc,
      parentId: new mongoose.Types.ObjectId(parentId),
      type: 'sub', createdAt: new Date(), updatedAt: new Date(),
    });
    subGroupMap[name] = result.insertedId.toString();
    console.log('  ✓ ' + name);
  }

  console.log('\n=== 迁移人物到一级阵营 + 二级子群体 ===');
  const persons = await db.collection('persons').find({}).toArray();
  let migrated = 0, unmapped = 0;

  for (const person of persons) {
    const name = person.name;
    const targetGroup = PERSON_GROUP[name];
    const targetSub = PERSON_TO_SUB[name];
    if (!targetGroup) {
      console.log('  ⚠️ 未映射: ' + name);
      unmapped++;
      continue;
    }
    const primaryId = primaryMap[targetGroup];
    if (!primaryId) { console.log('  ✗ 阵营不存在: ' + targetGroup); continue; }

    const groupIds = [new mongoose.Types.ObjectId(primaryId)];
    if (targetSub && subGroupMap[targetSub]) {
      groupIds.push(new mongoose.Types.ObjectId(subGroupMap[targetSub]));
    }

    await db.collection('persons').updateOne(
      { _id: person._id },
      { $set: { groupIds } }
    );
    migrated++;
  }

  console.log('迁移: ' + migrated + '  未映射: ' + unmapped);

  console.log('\n=== 最终统计 ===');
  const allPersons = await db.collection('persons').find({}).toArray();
  const allGroups = await db.collection('groups').find({}).toArray();
  const gMap: Record<string, string> = {};
  for (const g of allGroups) gMap[g._id.toString()] = g.name;
  const grouped = allPersons.filter(p => p.groupIds && p.groupIds.length > 0);
  const ungrouped = allPersons.filter(p => !p.groupIds || p.groupIds.length === 0);
  console.log('总人物: ' + allPersons.length + '  已关联: ' + grouped.length + '  未关联: ' + ungrouped.length);

  const counts: Record<string, number> = {};
  for (const p of grouped) {
    for (const gid of p.groupIds) {
      const gn = gMap[gid.toString()];
      if (gn) counts[gn] = (counts[gn] || 0) + 1;
    }
  }
  console.log('\n各阵营人数:');
  for (const [name, count] of Object.entries(counts).sort((a, b) => b[1] - a[1])) {
    console.log('  ' + name + ': ' + count);
  }

  await mongoose.disconnect();
}

main().catch(console.error);
